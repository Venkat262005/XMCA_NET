"""HALP: Hallucination Prediction via Pre-Generation Probing (EACL 2026).

Official methodology from Zesearch/HALP:
Predicts hallucination risk BEFORE a single token is generated by extracting
internal model representations during a single forward pass:
1. Visual Features (VF): Mean-pooled vision encoder outputs prior to multimodal projection.
2. Vision Tokens (VT): Hidden states at final vision-token positions across decoder layers.
3. Query Tokens (QT): Hidden states at final query-token positions fusing visual and textual context.

A 3-layer MLP probe predicts binary hallucination probability using BCE loss.
Calibrated strictly on validation split without test-label leakage.
"""

from typing import Dict, Any, Optional, Tuple, List
import numpy as np
import torch
import torch.nn as nn
from pydantic import BaseModel

from src.baselines.common_schema import BaselineDetectionOutput
from src.combiner.model import TemperatureScaler


class HALPProbeMLP(nn.Module):
    """Original HALP 3-layer MLP probing architecture (EACL 2026).
    
    Architecture:
    Input(D_hidden) -> Linear(512) -> LayerNorm -> GELU -> Dropout(0.1)
                   -> Linear(256) -> LayerNorm -> GELU -> Dropout(0.1)
                   -> Linear(1)
    """

    def __init__(self, input_dim: int, hidden_dim: int = 512, dropout: float = 0.1):
        super().__init__()
        self.probe = nn.Sequential(
            nn.Linear(input_dim, hidden_dim),
            nn.LayerNorm(hidden_dim),
            nn.GELU(),
            nn.Dropout(dropout),
            nn.Linear(hidden_dim, hidden_dim // 2),
            nn.LayerNorm(hidden_dim // 2),
            nn.GELU(),
            nn.Dropout(dropout),
            nn.Linear(hidden_dim // 2, 1),
        )

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        return self.probe(x).squeeze(-1)


class HALPProbeDetector:
    """Pre-generation hallucination probe detector (HALP EACL 2026).
    
    Preserves the official 11 distinct probe targets:
    - 1 Visual Feature (VF) probe on pooled vision tower outputs.
    - 5 Vision Token (VT) probes across intermediate/final decoder layers.
    - 5 Query Token (QT) probes across intermediate/final decoder layers.
    """

    PROBE_TARGETS = [
        "vf_pooled",
        "vt_pos_1", "vt_pos_L_div_4", "vt_pos_L_div_2", "vt_pos_3L_div_4", "vt_pos_L",
        "qt_pos_1", "qt_pos_L_div_4", "qt_pos_L_div_2", "qt_pos_3L_div_4", "qt_pos_L",
    ]

    def __init__(
        self,
        input_dim: int,
        probe_target: str = "qt_pos_L",
        hidden_dim: int = 128,
        lr: float = 1e-3,
    ):
        """Initialize HALP probe.
        
        Args:
            input_dim: Dimensionality of extracted hidden state (e.g. 4096 for LLaVA/Qwen2-VL).
            probe_target: One of 'visual_features', 'vision_tokens', 'query_tokens', 'ensemble'.
            hidden_dim: Hidden dimension of probe MLP.
            lr: Learning rate for probe optimization.
        """
        self.input_dim = input_dim
        self.probe_target = probe_target
        self.model = HALPProbeMLP(input_dim=input_dim, hidden_dim=hidden_dim)
        self.scaler = TemperatureScaler()
        self.is_fitted = False
        self.mean: Optional[np.ndarray] = None
        self.std: Optional[np.ndarray] = None
        self.lr = lr

    def fit(
        self,
        X_train: np.ndarray,
        y_train: np.ndarray,
        X_val: Optional[np.ndarray] = None,
        y_val: Optional[np.ndarray] = None,
        epochs: int = 30,
        batch_size: int = 64,
        pos_weight: Optional[float] = None,
    ):
        """Train HALP probe on training partition and calibrate on validation partition."""
        X_t = np.asarray(X_train, dtype=np.float32)
        y_t = np.asarray(y_train, dtype=np.float32)

        self.mean = np.mean(X_t, axis=0)
        self.std = np.std(X_t, axis=0)
        self.std[self.std < 1e-6] = 1.0
        X_norm = (X_t - self.mean) / self.std

        if pos_weight is None:
            n_pos = float(np.sum(y_t == 1))
            n_neg = float(np.sum(y_t == 0))
            pos_weight = n_neg / max(1.0, n_pos)

        criterion = nn.BCEWithLogitsLoss(pos_weight=torch.tensor([pos_weight], dtype=torch.float32))
        optimizer = torch.optim.AdamW(self.model.parameters(), lr=self.lr, weight_decay=1e-2)

        dataset = torch.utils.data.TensorDataset(
            torch.tensor(X_norm, dtype=torch.float32),
            torch.tensor(y_t, dtype=torch.float32),
        )
        loader = torch.utils.data.DataLoader(dataset, batch_size=batch_size, shuffle=True)

        self.model.train()
        for _ in range(epochs):
            for bx, by in loader:
                optimizer.zero_grad()
                logits = self.model(bx)
                loss = criterion(logits, by)
                loss.backward()
                optimizer.step()

        # Calibration on validation set
        self.model.eval()
        calib_X = X_val if X_val is not None else X_train
        calib_y = y_val if y_val is not None else y_train
        calib_norm = (np.asarray(calib_X, dtype=np.float32) - self.mean) / self.std

        with torch.no_grad():
            val_logits = self.model(torch.tensor(calib_norm, dtype=torch.float32))
            val_y_tensor = torch.tensor(np.asarray(calib_y, dtype=np.float32))
            self.scaler.calibrate(val_logits, val_y_tensor)

        self.is_fitted = True

    def to(self, device: str):
        """Move probe model and scaler to target device."""
        self.model.to(device)
        self.scaler.to(device)
        return self

    def predict_score(self, x: np.ndarray) -> float:
        """Predict continuous raw logit score for a single sample (higher = higher hallucination risk)."""
        self.model.eval()
        x_arr = np.asarray(x, dtype=np.float32)
        if self.mean is not None and self.std is not None:
            x_arr = (x_arr - self.mean) / self.std
        device = next(self.model.parameters()).device
        with torch.no_grad():
            x_tensor = torch.tensor(x_arr, dtype=torch.float32, device=device).unsqueeze(0)
            logit = self.model(x_tensor).item()
        return float(logit)

    def predict_calibrated_proba(self, x: np.ndarray) -> float:
        """Predict validation-calibrated risk probability in [0, 1]."""
        self.model.eval()
        x_arr = np.asarray(x, dtype=np.float32)
        if self.mean is not None and self.std is not None:
            x_arr = (x_arr - self.mean) / self.std
        device = next(self.model.parameters()).device
        with torch.no_grad():
            x_tensor = torch.tensor(x_arr, dtype=torch.float32, device=device).unsqueeze(0)
            logit = self.model(x_tensor)
            scaled = self.scaler(logit)
            prob = torch.sigmoid(scaled).item()
        return float(prob)
